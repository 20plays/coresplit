#!/usr/bin/env bash
# Install CoreSplit into the user's home. No root, no system packages.
set -euo pipefail

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/src"
APP_DIR="$HOME/.local/opt/coresplit"
BIN_DIR="$HOME/.local/bin"
APPS_DIR="$HOME/.local/share/applications"
ICON_DIR="$HOME/.local/share/icons/hicolor/scalable/apps"

say() { printf '  %s\n' "$*"; }

echo "Installing CoreSplit"

# -- dependency check ------------------------------------------------------- #
PYTHON=""
for candidate in python3 /usr/bin/python3; do
    if command -v "$candidate" >/dev/null 2>&1 && "$candidate" -c 'import PySide6' >/dev/null 2>&1; then
        PYTHON="$candidate"
        break
    fi
done
if [ -z "$PYTHON" ]; then
    echo "Error: no Python interpreter with PySide6 found." >&2
    echo "  pip install PySide6    (or: pacman -S python-pyside6)" >&2
    exit 1
fi
say "Python: $PYTHON"

# -- files ------------------------------------------------------------------ #
mkdir -p "$APP_DIR/assets" "$BIN_DIR" "$APPS_DIR" "$ICON_DIR"
install -m 0644 "$SRC_DIR"/*.py "$APP_DIR"/
install -m 0644 "$SRC_DIR"/assets/*.svg "$APP_DIR/assets/"
install -m 0644 "$SRC_DIR/assets/coresplit.svg" "$ICON_DIR/coresplit.svg"
say "Application: $APP_DIR"

# -- launcher --------------------------------------------------------------- #
cat > "$BIN_DIR/coresplit" <<'LAUNCHER'
#!/usr/bin/env bash
set -euo pipefail
APP_DIR="$HOME/.local/opt/coresplit"
for candidate in python3 /usr/bin/python3; do
    if command -v "$candidate" >/dev/null 2>&1 && "$candidate" -c 'import PySide6' >/dev/null 2>&1; then
        exec "$candidate" "$APP_DIR/coresplit.py" "$@"
    fi
done
echo "CoreSplit: no Python interpreter with PySide6 found." >&2
exit 1
LAUNCHER
chmod 0755 "$BIN_DIR/coresplit"
say "Launcher:   $BIN_DIR/coresplit"

# -- desktop entry ---------------------------------------------------------- #
cat > "$APPS_DIR/coresplit.desktop" <<DESKTOP
[Desktop Entry]
Type=Application
Name=CoreSplit
Comment=Keep games and background test workloads on separate CPU cores
Exec=$BIN_DIR/coresplit
Icon=coresplit
Terminal=false
Categories=Utility;System;
StartupWMClass=CoreSplit
DESKTOP
command -v update-desktop-database >/dev/null 2>&1 && \
    update-desktop-database "$APPS_DIR" 2>/dev/null || true
say "Menu entry: $APPS_DIR/coresplit.desktop"

# -- test wrapper ----------------------------------------------------------- #
# Generated by the app (Advanced -> Install testcpus wrapper), so it is not
# shipped; nothing to do here.

echo
echo "Done. Start it with:  coresplit"
echo
echo "Optional, for the most reliable game pinning, add this to Steam launch options:"
echo "  taskset -c <game-cpus> gamemoderun %command%"
echo "The app's Advanced tab copies the exact line for your CPU."
